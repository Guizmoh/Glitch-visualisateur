def main():
    names = list(ICONS)
    lines = ["/* generated by tools/gen_art.py: KAWA's icons (8 x 8) and the mascot (16 x 16, 2 bits) */",
             "#pragma once", "#include <stdint.h>",
             "enum { " + ", ".join(f"ICO_{n}" for n in names) + ", ICO_N };"]
    rows = []
    for n in names:
        img = ICONS[n]
        assert len(img) == 8 and all(len(r) == 8 for r in img), n
        rows.append("{" + ", ".join("0x%02X" % int(r.replace("#", "1").replace(".", "0"), 2) for r in img) + "}")
    lines.append("static const uint8_t ICONS[ICO_N][8] = {\n    " + ",\n    ".join(rows) + "};")
    ink = {".": 0, "o": 1, "b": 2, "w": 3}
    snames = list(SPRITES)
    lines.append("enum { " + ", ".join(f"SPR_{n}" for n in snames) + ", SPR_N };")
    srows = []
    for n in snames:
        img = SPRITES[n]
        assert len(img) == 16 and all(len(r) == 16 for r in img), n
        words = []
        for r in img:
            v = 0
            for x, ch in enumerate(r):
                v |= ink[ch] << (2 * x)
            words.append("0x%08Xu" % v)
        srows.append("{" + ", ".join(words) + "}")
    lines.append("static const uint32_t SPRITES[SPR_N][16] = {\n    " + ",\n    ".join(srows) + "};")
    OUT.write_text("\n".join(lines) + "\n")
    print("->", OUT, len(names), "icons,", len(snames), "sprites")


if __name__ == "__main__":
    main()
